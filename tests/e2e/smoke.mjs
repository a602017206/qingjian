import { mkdir } from 'node:fs/promises';
await mkdir('test-results',{recursive:true});
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:3415');
await page.waitForSelector('.home-heading');
await page.screenshot({path:'test-results/desktop-before.png',fullPage:true});
await page.locator('.sidebar-bottom > [data-action="settings"]').click();
await page.locator('#repo-form input[name="name"]').fill('个人笔记测试');
await page.locator('#repo-form button[type="submit"]').click();
await page.waitForFunction(()=>document.querySelector('.workspace-switch strong').textContent==='个人笔记测试',null,{timeout:3000});
await page.locator('[data-action="closeModal"]').click();
await page.setViewportSize({width:390,height:844});
const menuVisible=await page.locator('.mobile-menu').isVisible();
assert.equal(menuVisible,true,'窄屏必须显示导航入口');
assert.equal(errors.length,0,errors.join('\n'));
await browser.close();
console.log('表单提交和窄屏入口验证通过');
